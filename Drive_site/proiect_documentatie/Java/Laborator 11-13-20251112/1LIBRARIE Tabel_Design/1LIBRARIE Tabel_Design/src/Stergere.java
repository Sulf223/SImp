    private void StergereActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_StergereActionPerformed

        if (lista.getSelectedIndex() > -1) {
            try {
                stare = con.createStatement();
                String sterg = "DELETE from `carti` where `Titlu` like '" + titluInterfata + "'";
                stare.executeUpdate(sterg);
                JOptionPane.showMessageDialog(this, "Stergere efectuata cu succes", "EROARE", JOptionPane.ERROR_MESSAGE);
                //se reinitializeaza tabelul
                v = new Vector();
                lista.setListData(v);
                stare.close();
            } catch (SQLException sqle) {
                System.err.println("Eroare conectare: " + sqle);
            }
        } else {
            JOptionPane.showMessageDialog(this, "Nu s-a selectat nicio inregistrare", "EROARE", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_StergereActionPerformed

