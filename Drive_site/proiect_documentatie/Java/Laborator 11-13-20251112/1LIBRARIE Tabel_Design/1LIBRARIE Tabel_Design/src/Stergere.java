    private void cautareActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cautareActionPerformed
        titluInterfata = tfTitlu.getText();
        try {
            stare = con.createStatement();
            String intrebare = "SELECT * FROM `carti` where `Titlu`='" + titluInterfata + "'";

            ResultSet rezultat = stare.executeQuery(intrebare);
            int j = 0;
            while (rezultat.next()) {
                String titlu = rezultat.getString("Titlu");
                String autor = rezultat.getString("Autor");
                int nrpag = rezultat.getInt("NrPag");
                double pret = rezultat.getDouble("Pret");
                Carte c = new Carte(titlu, autor, nrpag, pret);
                v.addElement(c.afisare());
                lista.setListData(v);
                j++;
            }
            if (j == 0) {
                JOptionPane.showMessageDialog(rootPane, "Cartea cautata nu exista in BD");
            }

        } catch (SQLException sqle) {
            System.err.println("Eroare conectare: " + sqle);
        }
    }//GEN-LAST:event_cautareActionPerformed

